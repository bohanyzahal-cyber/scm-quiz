def wma(vals, p):
    """vals — מהישנה לחדשה; המשקל של האחרונה 1, ובכל תקופה אחורה מפחיתים p."""
    n = len(vals)
    ws = [1 - p * (n - 1 - i) for i in range(n)]
    return sum(v * w for v, w in zip(vals, ws)) / sum(ws), ws

