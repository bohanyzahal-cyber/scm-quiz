def add5(q, a, d, e, t, calc=True):
    assert len(d) == 4 and len(set([a] + list(d))) == 5, (a, d)
    it = dict(q=q, a=a, d=list(d), e=e + SRC, t=t, y=1)
    if calc:
        it["k"] = "calc"
    Q.append(it)


def o5(correct, cands, dec=0, unit="", pre=""):
    """(נכונה, [4 מסיחים]) באותו פורמט, שונים זה מזה אחרי העיגול."""
    c = pre + num(correct, dec) + unit
    out = []
    for v in cands:
        s = pre + num(v, dec) + unit
        if s != c and s not in out:
            out.append(s)
    assert len(out) == 4, (correct, cands, out)
    return c, out


def reg(ys):
    """רגרסיה על X = 1..n: מחזיר (a, b, r)."""
    n = len(ys)
    xs = list(range(1, n + 1))
    mx, my = sum(xs) / n, sum(ys) / n
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    b = sxy / sxx
    return my - b * mx, b, sxy / sqrt(sxx * syy)


def years(first, ys, label, nxt=True):
    head = ["שנה"] + [str(first + i) for i in range(len(ys))] + ([str(first + len(ys))] if nxt else [])
    return table(head, [[label] + [num(y, 0) for y in ys] + (["?"] if nxt else [])])


