n1 = ln(5 * 50 / 20)
add("משך טיפול מונע 4 שעות, משך תיקון שבר 10 שעות, 200 שעות עבודה בחודש, ובחודש בלי טיפולים מונעים מתרחשות 5 תקלות. מהו מספר הטיפולים המונעים האופטימלי בחודש (מינימום השבתה)?",
    *opts(n1, [ln(5 * 20 / 50), 5 * 50 / 20, ln(50 / 20)], dec=2),
    L("Ф = 200/4 = 50") + ", " + L("μ = 200/10 = 20") + ", f = 5.<br>" + L("n* = ln(f·Ф/μ) = ln(5·50/20) = ln(12.5) = 2.53") +
    ".<br>0.69 — היפוך Ф ו-μ; 12.50 — בלי ln; 0.92 — שכחת f. (מצגת 9, שקפים 9–12)")

add("נתון קצב ביקורות (טיפולים מונעים) אפשרי של 300 בחודש, קצב טיפולי שבר אפשרי של 30 בחודש, ו-f = 3. מהו n*?",
    *opts(ln(30), [ln(100), ln(10), 30], dec=2),
    L("n* = ln(f·Ф/μ) = ln(3·300/30) = ln(30) = 3.40") +
    ".<br>שימו לב: בשקף 10 של מצגת 9 מופיעה התוצאה 4.6 — זו טעות חישוב: 4.6 הוא " + L("ln(100)") +
    ", ולא מתאים לנתוני הדוגמה. 2.30 — שכחת f " + L("(ln 10)") + "; 30 — בלי ln. (מצגת 9, שקפים 9–10)")

n2 = ln(4 * (200 / 3) / (200 / 12))
lam2 = 4 * exp(-n2)
tdt = lam2 * 12 + n2 * 3
add("משך תיקון שבר 12 שעות, משך טיפול מונע 3 שעות, 200 שעות עבודה בחודש, ובחודש בלי טיפולים מונעים התרחשו 4 תקלות (n* = 2.77). "
    "מהו זמן ההשבתה הכולל בחודש (בשעות) בנקודה האופטימלית?",
    *opts(tdt, [n2 * 3, 4 * 12, lam2 * 12], dec=2),
    L("n* = ln(4·66.67/16.67) = ln(16) = 2.77") + "; " + L("λ(n*) = 4·e^(−2.77) = 0.25") + " תקלות בחודש.<br>"
    "השבתה בגין שבר: " + L("0.25 · 12 = 3") + " שעות; בגין טיפולים: " + L("2.77 · 3 = 8.32") + " שעות ← " + L("TDT = 11.32") +
    " שעות בחודש, לעומת " + L("4 · 12 = 48") + " שעות בלי טיפולים מונעים. (מצגת 9, שקפים 11–13)")

P, f, Fi, mu, Ci, Cr = 5000, 3, 80, 20, 1000, 5000
n3 = ln(f * Fi * (P + Cr) / (mu * (P + Ci)))
add("מודל מקסימום רווח: P = 5,000 $ לחודש, f = 3, קצב טיפולים מונעים אפשרי Ф = 80 בחודש, קצב תיקונים אפשרי μ = 20 בחודש, "
    + L("Ci = 1,000 $") + ", " + L("Cr = 5,000 $") + ". מהו n*?",
    *opts(n3, [ln(f * Fi / mu), ln(f * Fi * (P + Ci) / (mu * (P + Cr))), f * Fi * (P + Cr) / (mu * (P + Ci))], dec=2),
    L("n* = ln(f·Ф·(P + Cr) / (μ·(P + Ci))) = ln(3·80·10,000 / (20·6,000)) = ln(20) = 3.00") +
    ".<br>2.48 — נוסחת מינימום ההשבתה, בלי העלויות " + L("(ln 12)") + "; 1.97 — Ci ו-Cr הפוכים; 20.00 — בלי ln. "
    "כשעלות התיקון Cr גבוהה, כדאי לבצע יותר טיפולים מונעים. (מצגת 10, שקפים 8–12)")

P, f, Fi, mu, Ci, Cr = 10000, 2, 100, 25, 75, 400
n4 = ln(f * Fi * (P + Cr) / (mu * (P + Ci)))
lam4 = f * exp(-n4)
PR = P - P * n4 / Fi - P * lam4 / mu - Ci * n4 / Fi - Cr * lam4 / mu
PR_noC = P - P * n4 / Fi - P * lam4 / mu
PR0 = P - P * f / mu - Cr * f / mu
add("בדוגמה ממצגת 10: P = 10,000 $, f = 2, Ф = 100, μ = 25, " + L("Ci = 75 $") + ", " + L("Cr = 400 $") + ", ו-" + L("n* = 2.11") +
    ". מהו הרווח בנקודה האופטימלית?",
    *opts(PR, [PR_noC, PR0, P - P * n4 / Fi - P * f / mu - Ci * n4 / Fi - Cr * f / mu], dec=2, unit=" $"),
    L("λ(n*) = 2·e^(−2.11) = 0.242") + ".<br>" + L("PR = 10,000 − 10,000·2.11/100 − 10,000·0.242/25 − 75·2.11/100 − 400·0.242/25") + "<br>" +
    L("= 10,000 − 211.12 − 96.88 − 1.58 − 3.88 ≈ 9,686.55") + " $ (בשקף: 9,686).<br>"
    "9,692.01 — בלי עלויות הביקורת והתיקון; 9,168.00 — בלי טיפולים מונעים כלל (n = 0) — כלומר האחזקה המונעת מוסיפה כ-519 $ בחודש. (מצגת 10, שקפים 11–12)")

