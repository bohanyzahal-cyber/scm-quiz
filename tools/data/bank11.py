def fmt(v):
    """מספר לתצוגה: שלם אם שלם, אחרת שתי ספרות אחרי הנקודה; מפריד אלפים."""
    r = round(v, 2)
    if abs(r - round(r)) < 1e-9:
        return "{:,}".format(int(round(r)))
    return "{:,.2f}".format(r)

def L(s):
    """ביטוי חשבוני משמאל לימין בתוך טקסט עברי."""
    return "<bdi dir='ltr'>" + s + "</bdi>"

def table(label, vals, start=1, extra=None):
    """טבלת נתונים: שורת תקופות ושורת ערכים; extra = [(תווית, ערכים)] שורות נוספות."""
    n = len(vals)
    h = "<table><tr><th>תקופה</th>" + "".join("<th>%d</th>" % (start + i) for i in range(n)) + "</tr>"
    h += "<tr><th>%s</th>" % label + "".join("<td>%s</td>" % fmt(v) for v in vals) + "</tr>"
    for lab, row in (extra or []):
        h += "<tr><th>%s</th>" % lab + "".join("<td>%s</td>" % ("—" if v is None else fmt(v)) for v in row) + "</tr>"
    return h + "</table>"

def pick(correct, cands, unit=""):
    """שלושה מסיחים שונים מהנכונה ומזה מזה (בהשוואה אחרי עיגול לתצוגה)."""
    c = fmt(correct)
    out = []
    for v in cands:
        s = fmt(v)
        if s != c and s not in out:
            out.append(s)
        if len(out) == 3:
            break
    assert len(out) == 3, (correct, cands)
    return [x + unit for x in out]


def numopts(correct, cands):
    """הנכונה + שלושה מסיחים, בפורמט אחיד: אם אחת האפשרויות אינה שלמה — כולן בשתי ספרות."""
    ds = pick(correct, cands)
    vals = [round(correct, 2)] + [float(x.replace(",", "")) for x in ds]
    if all(abs(v - round(v)) < 1e-9 for v in vals):
        return fmt(correct), ds
    f2 = lambda v: "{:,.2f}".format(round(v, 2))
    return f2(correct), [f2(v) for v in vals[1:]]

def ma(y, N, t):            # תחזית לתקופה t (1-based) בממוצע נע פשוט
    return sum(y[t-1-N:t-1]) / N

def weights(n, step):       # משקולות צמודות לתקופות 1..n
    return [round(1 - step * (n - 1 - i), 4) for i in range(n)]

def wma(y, W, N, t):        # תחזית לתקופה t עם משקולות צמודות
    idx = range(t-1-N, t-1)
    return sum(y[i]*W[i] for i in idx) / sum(W[i] for i in idx)

def reg(y):
    n = len(y); x = list(range(1, n+1))
    sx, sy = sum(x), sum(y)
    sxy = sum(a*b for a, b in zip(x, y)); sxx = sum(a*a for a in x); syy = sum(b*b for b in y)
    b = (n*sxy - sx*sy) / (n*sxx - sx*sx)
    a = sy/n - b*sx/n
    r = (n*sxy - sx*sy) / math.sqrt((n*sxx - sx*sx) * (n*syy - sy*sy))
    return dict(n=n, sx=sx, sy=sy, sxy=sxy, sxx=sxx, syy=syy, b=b, a=a, r=r)

def mad_mse(act, fc):
    d = [abs(a - f) for a, f in zip(act, fc)]
    return sum(d)/len(d), sum(v*v for v in d)/len(d), d

